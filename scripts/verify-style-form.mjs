import assert from 'node:assert/strict'
import {chromium} from 'file:///C:/Users/Lenovo/AppData/Local/Temp/jellyfish-browser-check/node_modules/playwright/index.mjs'
/** 正式页面只读验证紧凑表单和混合题材前端校验，不保存项目或调用模型。 */
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1366,height:768}})
const errors=[],writes=[]
page.on('pageerror',e=>errors.push(e.message))
await page.route('**/api/**',route=>{if(!['GET','OPTIONS'].includes(route.request().method())){writes.push(route.request().url());return route.abort()}return route.continue()})
try{
 await page.goto('http://127.0.0.1:7788/projects')
 await page.getByText('新建项目',{exact:true}).click()
 const modal=page.getByRole('dialog')
 await modal.getByRole('combobox',{name:'画面表现'}).waitFor()
 assert.equal(await modal.getByRole('combobox',{name:'表现形式',exact:true}).count(),0)
 await modal.getByRole('button',{name:'3D修真',exact:true}).click()
 assert.match(await modal.innerText(),/动漫 · 3D国漫/)
 await modal.getByText('补充设定（可选）',{exact:true}).click()
 await modal.getByRole('combobox',{name:'辅助题材'}).click()
 assert.equal(await page.locator('.ant-select-dropdown:visible').getByText('玄幻修真',{exact:true}).count(),0)
 await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({hasText:/^都市生活$/}).click()
 await page.keyboard.press('Escape')
 await modal.getByRole('textbox',{name:'混合题材说明'}).waitFor()
 assert.match(await modal.innerText(),/混合题材需填写融合说明/)
 await modal.getByRole('textbox',{name:'混合题材说明'}).fill('现代都市中修炼者隐居，普通人不知道法术存在')
 await modal.getByRole('tab',{name:'世界与美术',exact:true}).click()
 assert.match(await modal.getByRole('textbox',{name:'时代',exact:true}).getAttribute('placeholder'),/架空古代/)
 assert.match(await modal.getByRole('textbox',{name:'世界规则',exact:true}).inputValue(),/修炼者隐居/)
 const box=await modal.boundingBox();assert.ok(box.width<=1366)
 await modal.getByRole('button',{name:/取\s*消/}).click()
 await page.goto('http://127.0.0.1:7788/assets?tab=actor')
 await page.getByRole('button',{name:/新建/}).first().click()
 const asset=page.getByRole('dialog')
 await asset.getByText('补充设定（可选）',{exact:true}).click()
 await asset.getByRole('tab',{name:'世界与美术',exact:true}).click()
 const create=await asset.getByRole('button',{name:/创\s*建/}).boundingBox()
 assert.ok(create&&create.y+create.height<=768,'演员创建按钮应在视口内')
 assert.deepEqual(errors,[]);assert.deepEqual(writes,[])
 console.log('PASS 基础两项、主辅排重、融合说明联动、世界说明示例、零写入和页面错误')
}finally{await browser.close()}
